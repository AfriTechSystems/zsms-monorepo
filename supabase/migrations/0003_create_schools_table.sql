CREATE TABLE IF NOT EXISTS public.schools (
  id                      UUID DEFAULT gen_random_uuid() PRIMARY KEY,

  school_id               TEXT UNIQUE NOT NULL,
  -- Format: ZM-LSK-0001 (country_code-city_code-sequence).
  -- Generated by the school onboarding Edge Function. Never manually assigned.

  clerk_org_id            TEXT UNIQUE NOT NULL,
  -- The Clerk Organisation ID for this school. This is the tenant key:
  -- get_school_id() returns it from the JWT, and every RLS policy in the
  -- system resolves tenancy through this column.

  country_code            TEXT NOT NULL DEFAULT 'ZM'
                          CHECK (country_code ~ '^[A-Z]{2}$'),

  name                    TEXT NOT NULL,
  type                    TEXT NOT NULL
                          CHECK (type IN ('day', 'boarding', 'both')),
  level                   TEXT NOT NULL
                          CHECK (level IN ('pre', 'primary', 'secondary', 'combined')),
  city_code               TEXT NOT NULL,

  address                 TEXT,
  phone                   TEXT,
  email                   TEXT,
  logo_url                TEXT,

  status                  TEXT NOT NULL DEFAULT 'pending_verification'
                          CHECK (status IN (
                            'pending_verification',
                            'trial',
                            'active',
                            'suspended',
                            'terminated'
                          )),

  subscription_tier       TEXT NOT NULL DEFAULT 'starter'
                          CHECK (subscription_tier IN (
                            'starter', 'growth', 'professional', 'enterprise'
                          )),

  trial_ends_at           TIMESTAMPTZ,
  subscription_ends_at    TIMESTAMPTZ,

  finance_module_enabled  BOOLEAN NOT NULL DEFAULT FALSE,
  whatsapp_enabled        BOOLEAN NOT NULL DEFAULT TRUE,

  max_students            INT,
  -- NULL means unlimited (Professional and Enterprise tiers).

  created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.schools IS
  'Root tenant table. clerk_org_id is the tenant key that every RLS policy resolves through.';
COMMENT ON COLUMN public.schools.clerk_org_id IS
  'Clerk Organisation ID. Matched against get_school_id() in every tenant-scoped RLS policy.';

CREATE INDEX IF NOT EXISTS idx_schools_status     ON public.schools(status);
CREATE INDEX IF NOT EXISTS idx_schools_country    ON public.schools(country_code);
CREATE INDEX IF NOT EXISTS idx_schools_clerk_org  ON public.schools(clerk_org_id);

DROP TRIGGER IF EXISTS update_timestamp_on_schools ON public.schools;
CREATE TRIGGER update_timestamp_on_schools
  BEFORE UPDATE ON public.schools
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Table privileges. RLS is the tenant boundary, but privileges are the outer
-- gate: anon has no reason to touch this table at all. No DELETE — schools are
-- never hard deleted (CONVENTIONS.md prohibition 8; status carries termination).
REVOKE ALL ON public.schools FROM anon;
GRANT SELECT, INSERT, UPDATE ON public.schools TO authenticated;

-- ---------------------------------------------------------------------------
-- current_school_uuid() — tenant key resolution
-- ---------------------------------------------------------------------------
-- get_school_id() returns the Clerk org ID (TEXT); every tenant-scoped table
-- keys on schools.id (UUID). Rather than repeating the lookup subquery in
-- every policy, resolve it once here.
--
-- SECURITY DEFINER is required, not a convenience. Inlining
--   school_id = (SELECT id FROM public.schools WHERE clerk_org_id = get_school_id())
-- makes every policy evaluation re-enter the schools table under RLS. That is
-- both a per-row cost and a recursion risk once other tables' policies
-- reference each other. Reading one's own school row is already permitted by
-- 0004, so resolving it with definer rights widens nothing.
CREATE OR REPLACE FUNCTION public.current_school_uuid()
RETURNS UUID
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT id FROM public.schools WHERE clerk_org_id = public.get_school_id();
$$;

COMMENT ON FUNCTION public.current_school_uuid() IS
  'Resolves the JWT Clerk org ID to schools.id. SECURITY DEFINER to avoid re-entering schools RLS from every tenant policy.';

GRANT EXECUTE ON FUNCTION public.current_school_uuid() TO authenticated;

